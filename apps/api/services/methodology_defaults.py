"""
The starting speech standard of a new company: one module for each audit criterion that can be said aloud.

The numbering is the audit's (cr1..cr13, apps/api/services/prompt_builder.py): the methodology measures the same
criteria the call audit marks. The texts are neutral templates, nothing about any vendor or price: a company edits
them to its own script. In an anchor, "|" separates interchangeable wordings (see script_adherence.py).
cr11 "Слушание клиента" has no module: the code measures it by the client's share of the words, it is not a phrase.
"""

