CRITERIA_IDS = [f"cr{i}" for i in range(1, N_CRITERIA + 1)]


def criterion_title(criterion: str) -> str:
    return str(BASE_10_CRITERIA.get(criterion, {}).get("title") or criterion)


def criterion_meta(criterion: str) -> dict[str, str]:
    return {"title": criterion_title(criterion), "stage": STAGES.get(criterion, criterion)}


def _m(cr: str, speech: str, anchors: list[str], banned: list[str], min_anchors: int) -> dict[str, Any]:
    return {
        "target_criterion": cr,
        "stage_name": STAGES[cr],
        "recommended_speech": speech,
        "semantic_anchors": anchors,
        "banned_triggers": banned,
        "min_anchors_required": min_anchors,
    }


